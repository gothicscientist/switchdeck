import {readFile,writeFile} from 'node:fs/promises';
import {loadFullCatalog} from './catalog-pack.mjs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import '../assets/affiliates.js';
import '../assets/product-links.js';
const {productURL,orderLinks}=globalThis.SwitchdeckLinks;
const root=new URL('../',import.meta.url);
const read=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
// Conservative identity: keep revision, profile, kit, pack and material words.
// No fuzzy model matching, and no cross-brand or cross-category substitutions.
export const identity=p=>[p.category||p.cat,p.brand,p.name].map(s=>String(s||'').normalize('NFKC').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim()).join('|');
export async function buildProductLinks(){
  const manifest=await read('data/catalog-manifest.json');
  const products=(await Promise.all(manifest.shards.map(s=>read('data/'+s)))).flat();
  const overrides=await read('scripts/product-link-overrides.json');
  const matches=await read('scripts/curated-matches.json');
  const curated=await read('scripts/curated-parts.json');
  const groups=new Map(),registry={};
  for(const p of products){
    if(!productURL(p.url))throw Error('Non-product catalog URL: '+p.id);
    const key=identity(p);if(!groups.has(key))groups.set(key,[]);
    groups.get(key).push({name:p.retailer,url:p.url,available:p.available,checkedAt:p.checkedAt});
  }
  for(const p of products){const links=orderLinks(groups.get(identity(p)));if(links.length>1)registry[p.id]=links}
  const byId=new Map(products.map(p=>[p.id,p]));
  const cat=await loadFullCatalog(new URL('data/',root));
  for(const p of curated){
    const meta=cat.curated?.[p.id];
    registry[p.id]=orderLinks([...(meta?.retailers||[]),...(p.photo?.page?[{name:p.brand,url:p.photo.page}]:[])]);
  }
  for(const [id,entry] of Object.entries(overrides)){
    if(!byId.has(id)&&!curated.some(p=>p.id===id))throw Error('Unknown override product: '+id);
    const additions=[];
    for(const link of entry.links){
      if(!productURL(link.url)||!link.title||!link.evidenceUrl||!Number.isFinite(Date.parse(link.checkedAt)))throw Error('Product evidence required: '+id);
      additions.push(link);
    }
    registry[id]=orderLinks([...additions,...(registry[id]||[])]);
    // Reuse only the version-specific identities that have already been reviewed
    // for this curated part. Never infer an ASIN from a name or invent a URL.
    for(const listingId of matches[id]||[])if(byId.has(listingId))registry[listingId]=orderLinks([...additions,...(registry[listingId]||[])]);
  }
  // Variant-specific source URLs remain first within their retailer. Do not replace
  // an exact variant with another store's vaguely similar pack or spring weight.
  // Single-source builder parts already carry exact variant URLs in retailers.
  const missing=curated.filter(p=>!registry[p.id]?.length).map(p=>({id:p.id,name:p.brand+' '+p.name,reason:'No confirmed exact product listing; no search/homepage substituted.'}));
  const report={generatedAt:new Date().toISOString(),catalogProducts:products.length,curatedProducts:curated.length,curatedLinked:curated.length-missing.length,amazonProducts:Object.values(registry).filter(r=>r.some(l=>globalThis.SwitchdeckLinks.isAmazon(l.url))).length,missing};
  await writeFile(new URL('data/product-links.js',root),'/* Generated by npm run catalog:links. Exact product pages; Amazon first, then affiliate stores. */\nglobalThis.SWITCHDECK_PRODUCT_LINKS = '+JSON.stringify(registry)+';\n');
  await writeFile(new URL('data/product-link-report.json',root),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));return report;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildProductLinks();
